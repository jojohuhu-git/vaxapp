const MODE_LABELS = {
  fewestVisits: 'Fewest visits',
  earliestCompletion: 'Earliest completion',
  fewestInjections: 'Fewest injections (combo brands prioritized)',
};

function fmtRiskList(risks) {
  if (!risks || risks.length === 0) return 'None entered';
  return risks.join(', ');
}

function ageAtDateStr(dob, date) {
  if (!dob) return '';
  const ms = new Date(date) - new Date(dob);
  const days = ms / (1000 * 60 * 60 * 24);
  const months = days / 30.4375;
  if (months < 24) return `${Math.round(months)} months`;
  return `${(months / 12).toFixed(1)} years`;
}

function GeneratedHeader({ today }) {
  return (
    <>
      <Text style={styles.generatedLine}>Generated {today} · For clinician review</Text>
      <Text style={styles.staleLine}>
        These dates assume every dose is given on time. If a dose is missed or given early, ask for a new copy.
      </Text>
    </>
  );
}

function Disclaimer({ today }) {
  return (
    <>
      <View style={styles.providerBlock}>
        <Text style={styles.providerLabel}>Provider / Clinic:</Text>
        <View style={styles.providerLine} />
        <Text style={styles.providerLabel}>Clinician signature / date:</Text>
        <View style={styles.providerLine} />
      </View>

      <View style={styles.disclaimer}>
        <Text>
          {'DISCLAIMER: This schedule is generated by PediVax for clinician review and is NOT medical advice. All dose timing, brand selection, and contraindication review must be verified against current CDC/ACIP guidance and the manufacturer\'s prescribing information before any vaccine is administered. Schedule may change based on availability, intercurrent illness, contraindications, or new clinical findings. PediVax authors and operators assume no responsibility for clinical decisions made on the basis of this output.'}
        </Text>
      </View>

      <Text
        style={styles.footer}
        fixed
        render={({ pageNumber, totalPages }) =>
          `PediVax · Generated ${today} · Page ${pageNumber} of ${totalPages}`
        }
      />
    </>
  );
}

function RoutineBody({ am, dob, risks, rows }) {
  const dobFmt = dob
    ? new Date(dob + 'T12:00:00').toLocaleDateString('en-US', {
        month: 'short', day: 'numeric', year: 'numeric',
      })
    : null;

  const visibleRows = rows.filter(r => r.isCurr || r.items.length > 0);

  return (
    <>
      <View style={styles.metaRow}>
        <Text style={styles.metaLabel}>Patient name:</Text>
        <Text style={styles.metaValue}>_____________________________</Text>
      </View>
      {dobFmt && (
        <View style={styles.metaRow}>
          <Text style={styles.metaLabel}>Date of birth:</Text>
          <Text style={styles.metaValue}>{dobFmt}</Text>
        </View>
      )}
      <View style={styles.metaRow}>
        <Text style={styles.metaLabel}>Current age:</Text>
        <Text style={styles.metaValue}>{fmtAm(am)}</Text>
      </View>
      {risks && risks.length > 0 && (
        <View style={styles.metaRow}>
          <Text style={styles.metaLabel}>Risk factors:</Text>
          <Text style={styles.metaValue}>{fmtRiskList(risks)}</Text>
        </View>
      )}

      <Text style={styles.h2}>Visit-by-visit forecast</Text>

      {visibleRows.map((row, i) => {
        const bgColor = row.isCurr ? '#2e7d32'
          : row.isCatchup ? '#b45309'
          : row.isPast ? '#888'
          : '#1a3a6b';

        const visitLabel = row.isCurr
          ? `▶ ${row.l} — CURRENT VISIT`
          : row.isCatchup ? `${row.l} (catch-up)`
          : row.l;

        return (
          <View key={i} wrap={false}>
            <View style={[styles.visitHeader, { backgroundColor: bgColor }]}>
              <Text style={[styles.visitHeaderText, { flex: 1 }]}>{visitLabel}</Text>
              {row.date
                ? <Text style={styles.visitHeaderText}>{row.date}</Text>
                : null}
            </View>
            <View style={styles.visitBox}>
              {row.items.length > 0
                ? row.items.map((item, j) => {
                    const brandShort = item.brand
                      ? item.brand.split('(')[0].trim()
                      : '(brand to select)';
                    return (
                      <View key={j} style={styles.doseRow}>
                        <Text style={styles.doseVk}>{item.vk}</Text>
                        <Text style={styles.doseDose}>{item.chip}</Text>
                        <Text style={styles.doseBrand}>{brandShort}</Text>
                        {item.date
                          ? <Text style={styles.doseDate}>{item.date}</Text>
                          : null}
                      </View>
                    );
                  })
                : <Text style={{ fontSize: 9, color: '#888' }}>No vaccines due</Text>}
            </View>
          </View>
        );
      })}
    </>
  );
}

function VisitItems({ items, chipCtx }) {
  return (
    <>
      {items.map((it, i) => {
        if (it._combo) {
          return (
            <View key={i} style={styles.comboRow} wrap={false}>
              <Text style={styles.comboName}>{it.comboName}</Text>
              <Text style={styles.comboCovers}>
                covers {it.coveredAntigens.join(' + ')} (
                {it.coveredDoses.map(d => `${d.vk} ${compactDoseChipLabel(d.vk, d.doseNum, d.totalDoses, chipCtx)}`).join(', ')})
              </Text>
            </View>
          );
        }
        const brandShort = it.brand ? it.brand.split('(')[0].trim() : '(brand to select)';
        return (
          <View key={i} style={styles.doseRow} wrap={false}>
            <Text style={styles.doseVk}>{it.vk}</Text>
            <Text style={styles.doseNum}>{compactDoseChipLabel(it.vk, it.doseNum, it.totalDoses, chipCtx)}</Text>
            <Text style={styles.doseBrand}>{brandShort}</Text>
          </View>
        );
      })}
    </>
  );
}

function OptimizerBody({ patient, mode, visits }) {
  // N4: what the dose chips need before printing a total — some meningococcal
  // schedules never finish. See compactDoseChipLabel in dosePlan.js.
  const chipCtx = { risks: patient.risks || [], hist: patient.hist || {}, dob: patient.dob || null };
  const totalDoses = visits.reduce((s, v) => s + v.items.reduce((s2, it) => s2 + (it._combo ? it.coveredDoses.length : 1), 0), 0);
  const totalInjections = visits.reduce((s, v) => s + v.items.length, 0);
  const lastVisitDate = visits.at(-1)?.date;

  return (
    <>
      <View style={styles.metaRow}>
        <Text style={styles.metaLabel}>Patient name:</Text>
        <Text style={styles.metaValue}>{patient.name || '_____________________________'}</Text>
      </View>
      <View style={styles.metaRow}>
        <Text style={styles.metaLabel}>Date of birth:</Text>
        <Text style={styles.metaValue}>{patient.dob || '_____________'}</Text>
      </View>
      <View style={styles.metaRow}>
        <Text style={styles.metaLabel}>Current age:</Text>
        <Text style={styles.metaValue}>{patient.am} months</Text>
      </View>
      <View style={styles.metaRow}>
        <Text style={styles.metaLabel}>Risk conditions:</Text>
        <Text style={styles.metaValue}>{fmtRiskList(patient.risks)}</Text>
      </View>
      <View style={styles.metaRow}>
        <Text style={styles.metaLabel}>Schedule mode:</Text>
        <Text style={styles.metaValue}>{MODE_LABELS[mode] || mode}</Text>
      </View>

      <Text style={styles.h2}>Summary</Text>
      <Text>{visits.length} visits · {totalInjections} injections ({totalDoses} antigen doses) · series complete by {lastVisitDate || 'N/A'}</Text>

      <Text style={styles.h2}>Visit-by-visit plan</Text>
      {visits.map((v, i) => (
        <View key={i} wrap={false}>
          <View style={[styles.visitHeader, { backgroundColor: '#1a3a6b' }]}>
            <Text style={[styles.visitHeaderText, { flex: 1 }]}>Visit {i + 1} — {v.date}</Text>
            <Text style={styles.visitHeaderText}>
              Age: {ageAtDateStr(patient.dob, v.date)} · {v.items.length} injection{v.items.length !== 1 ? 's' : ''}
            </Text>
          </View>
          <View style={styles.visitBox}>
            <VisitItems items={v.items} chipCtx={chipCtx} />
          </View>
        </View>
      ))}
    </>
  );
}

export default function SchedulePDF(props) {
  const { am, dob, risks, rows, patient, mode, visits, recs, fcBrands, generatedAt } = props;
  const isOptimizer = Array.isArray(visits);

  const today = generatedAt || (isOptimizer
    ? todayISO()
    : new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' }));

  const title = isOptimizer ? 'Optimal Vaccine Schedule' : 'Full Immunization Forecast';
  const docTitle = isOptimizer
    ? `PediVax Schedule — ${patient?.name || 'Patient'} (${today})`
    : `PediVax Full Forecast — ${today}`;
  const shotListAm = isOptimizer ? patient.am : am;
  const shotListDob = isOptimizer ? patient.dob : dob;

  return (
    <Document title={docTitle} author="PediVax">
      {/* Today's admin/shot-list page first, then the visit-by-visit plan —
          one download covers both what to give today and what's coming. */}
      {recs && recs.length > 0 && <ShotListPage am={shotListAm} dob={shotListDob} recs={recs} fcBrands={fcBrands} />}
      <Page size="LETTER" style={styles.page}>
        <Text style={styles.h1}>{title}</Text>
        <GeneratedHeader today={today} />

        <View style={styles.divider} />

        {isOptimizer
          ? <OptimizerBody patient={patient} mode={mode} visits={visits} />
          : <RoutineBody am={am} dob={dob} risks={risks} rows={rows} />}

        <Disclaimer today={today} />
      </Page>
    </Document>
  );
}
