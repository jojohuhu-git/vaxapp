// SchedulePDF.jsx — the one clinician-facing schedule PDF (D10). Merged from
// the former separate ForecastPDF.jsx (routine ACIP timeline) and this file's
// prior optimizer-only version: same document shape, same disclaimer/footer,
// two body layouts selected by which props are passed. `visits` present means
// the optimizer's combo-bundled plan; otherwise it's the routine forecast
// built from `rows`. No family-facing template — this is for the clinician.
